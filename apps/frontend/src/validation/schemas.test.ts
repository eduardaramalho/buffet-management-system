import { describe, expect, it } from 'vitest'
import { clientFormSchema } from './clientSchema'
import { collaboratorFormSchema } from './collaboratorSchema'
import { eventFormSchema } from './eventSchema'
import { hasErrorIn, toFieldErrors } from './fieldErrors'
import { roleFormSchema } from './roleSchema'
import { ruleFormSchema } from './ruleSchema'
import { integerText } from './rules'
import { serviceFormSchema } from './serviceSchema'
import { taskFormSchema } from './taskSchema'
import { teamFormSchema } from './teamSchema'
import { userCreateFormSchema, userUpdateFormSchema } from './userSchema'
import type { z } from 'zod'

const errorsOf = (schema: z.ZodType, values: unknown) => {
  const result = schema.safeParse(values)
  return result.success ? {} : toFieldErrors(result.error)
}

describe('form schemas (mirror of the backend Zod rules)', () => {
  it('keeps only the first message per field and finds errors of list items', () => {
    const errors = errorsOf(roleFormSchema, { name: '', description: '' })
    expect(errors).toEqual({ name: 'Informe o nome do papel.' })
    expect(hasErrorIn({ 'taskTemplates.0.title': 'x' }, ['taskTemplates'])).toBe(true)
    expect(hasErrorIn({ name: 'x' }, ['taskTemplates'])).toBe(false)
  })

  it('validates integers typed as text', () => {
    const optional = integerText({ min: 0, max: 10 })
    expect(optional.safeParse('').success).toBe(true)
    expect(errorsOf(integerText({ required: 'Obrigatório', min: 1, max: 10 }), '')).toEqual({ '': 'Obrigatório' })
    expect(errorsOf(optional, '1.5')).toEqual({ '': 'Informe um número inteiro.' })
    expect(errorsOf(integerText({ min: 2, max: 10 }), '1')).toEqual({ '': 'O valor mínimo é 2.' })
    expect(errorsOf(optional, '11')).toEqual({ '': 'O valor máximo é 10.' })
  })

  it('validates the client document by type', () => {
    const base = { type: 'PJ', name: 'Empresa', document: '11.222.333/0001-82', email: '', phone: '', notes: '' }
    expect(errorsOf(clientFormSchema, base)).toEqual({ document: 'CNPJ inválido. Confira os caracteres digitados.' })
    expect(errorsOf(clientFormSchema, { ...base, document: '11.222.333/0001-81' })).toEqual({})
    expect(errorsOf(clientFormSchema, { ...base, name: 'a'.repeat(151) })).toMatchObject({ name: 'Use no máximo 150 caracteres.' })
  })

  it('validates collaborators, teams and services', () => {
    expect(errorsOf(collaboratorFormSchema, { name: 'Ana', position: 'Garçom', phone: '(47) 3333-4444' })).toEqual({})
    expect(errorsOf(teamFormSchema, { name: 'Equipe', specialty: '', observations: '' })).toEqual({ specialty: 'Selecione a especialidade.' })
    expect(errorsOf(serviceFormSchema, { name: '   ' })).toEqual({ name: 'Informe o nome do serviço.' })
  })

  it('validates users like the UserController', () => {
    expect(errorsOf(userCreateFormSchema, { name: 'A', email: 'x', password: '123', roleId: '' })).toEqual({
      name: 'Use pelo menos 2 caracteres.',
      email: 'Informe um e-mail válido, por exemplo nome@empresa.com.',
      password: 'A senha precisa ter pelo menos 8 caracteres.',
      roleId: 'Selecione o papel do usuário.',
    })
    expect(errorsOf(userUpdateFormSchema, { name: 'Ana', email: '' })).toEqual({ email: 'Informe o e-mail.' })
  })

  it('skips the title of a task generated by a rule', () => {
    const values = { eventId: 'e1', title: '', description: '', dueDate: '', assignedTeamId: '' }
    expect(errorsOf(taskFormSchema(true), values)).toEqual({})
    expect(errorsOf(taskFormSchema(false), values)).toEqual({ title: 'Informe o título da tarefa.' })
  })

  it('validates events and rules', () => {
    const event = { clientId: 'c', name: 'Festa', eventDate: '2026-12-12T19:00', serviceType: 'CASAMENTO', location: 'Salão', guestsCount: '0', observations: '', customSelected: false, customLabel: '' }
    expect(errorsOf(eventFormSchema, event)).toEqual({ guestsCount: 'O evento precisa ter pelo menos 1 convidado.' })
    expect(errorsOf(eventFormSchema, { ...event, name: 'Fe', guestsCount: '10' })).toEqual({ name: 'Use pelo menos 3 caracteres.' })

    const rule = { name: 'Regra', description: '', minGuests: '', maxGuests: '', resourceRequirements: [{ specialty: 'BAR', minQuantity: '0' }], taskTemplates: [{ title: 'Montar', daysBeforeEvent: '400', specialty: '' }] }
    expect(errorsOf(ruleFormSchema, rule)).toEqual({
      'resourceRequirements.0.minQuantity': 'A quantidade mínima é 1.',
      'taskTemplates.0.daysBeforeEvent': 'Use no máximo 365 dias.',
    })
    const tooMany = { ...rule, resourceRequirements: [], taskTemplates: Array.from({ length: 21 }, () => ({ title: 'T', daysBeforeEvent: '', specialty: '' })) }
    expect(errorsOf(ruleFormSchema, tooMany)).toEqual({ taskTemplates: 'Uma regra pode gerar no máximo 20 tarefas.' })
  })
})
