import axios from 'axios'
import { httpClient } from './httpClient'
import { filenameFromDisposition, saveBlob } from '../utils/download'
import type { ApiPeriod } from '../utils/reportPeriod'
import type {
  EventReportFilters,
  EventsReport,
  ExportFormat,
  PageParams,
  ReportKind,
  TaskReportFilters,
  TasksReport,
  TeamPerformanceReport,
} from '../types/report'

type Filters = EventReportFilters | TaskReportFilters | Record<string, never>

// Empty select values must not reach the API as "status=" (the enum validation would answer 422).
const compact = (filters: Filters) => Object.fromEntries(Object.entries(filters).filter(([, value]) => value !== undefined && value !== ''))

export const getEventsReport = async (period: ApiPeriod, filters: EventReportFilters, page: PageParams) =>
  (await httpClient.get<EventsReport>('/api/v1/reports/events', { params: { ...period, ...compact(filters), ...page } })).data

export const getTasksReport = async (period: ApiPeriod, filters: TaskReportFilters, page: PageParams) =>
  (await httpClient.get<TasksReport>('/api/v1/reports/tasks', { params: { ...period, ...compact(filters), ...page } })).data

export const getTeamPerformanceReport = async (period: ApiPeriod) =>
  (await httpClient.get<TeamPerformanceReport>('/api/v1/reports/teams-performance', { params: period })).data

function parseJson(text: string): unknown {
  try { return JSON.parse(text) } catch { return undefined }
}

/**
 * Downloads the export generated by the API. With responseType "blob", error bodies also arrive as Blob;
 * they are parsed back to JSON so getApiErrorMessage can show the server message.
 */
export async function downloadReport(kind: ReportKind, period: ApiPeriod, filters: Filters, format: ExportFormat) {
  try {
    const response = await httpClient.get<Blob>(`/api/v1/reports/${kind}/export`, { params: { ...period, ...compact(filters), format }, responseType: 'blob' })
    const filename = filenameFromDisposition(response.headers['content-disposition'], `relatorio-${kind}.${format}`)
    saveBlob(response.data, filename)
  } catch (cause) {
    if (axios.isAxiosError(cause) && cause.response?.data instanceof Blob) {
      cause.response.data = parseJson(await cause.response.data.text())
    }
    throw cause
  }
}
